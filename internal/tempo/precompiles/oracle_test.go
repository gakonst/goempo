// The oracle corpus: precompile calls generated by zempo's tools/cases and run
// through the reference's own precompiles (tempoxyz/tempo, zempo tools/oracle
// precompile_call) over the same pre-state. Each case is one call; the
// expected outcome is its status, output, gas, refund, logs, changed slots and
// changed accounts. The corpus lives in zempo's repository
// (src/tempo/precompiles/testdata), copied here as testdata/oracle.tar.gz.
// testdata/oracle_known.txt lists the cases that still differ.

type oracleAccount struct {
	Address    string      `json:"address"`
	Code       *string     `json:"code"`
	Commitment *string     `json:"commitment"`
	Storage    [][2]string `json:"storage"`
}

type oracleCase struct {
	Name  string `json:"name"`
	Spec  string `json:"spec"`
	Block struct {
		Number      uint64 `json:"number"`
		Timestamp   uint64 `json:"timestamp"`
		Beneficiary string `json:"beneficiary"`
	} `json:"block"`
	Accounts  []oracleAccount `json:"accounts"`
	Transient []struct {
		Address string `json:"address"`
		Slot    string `json:"slot"`
		Value   string `json:"value"`
	} `json:"transient"`
	Call struct {
		Caller      string `json:"caller"`
		Target      string `json:"target"`
		CodeAddress string `json:"code_address"`
		Data        string `json:"data"`
		Gas         uint64 `json:"gas"`
		Static      bool   `json:"static"`
	} `json:"call"`
}

type oracleSlot struct {
	Address string `json:"address"`
	Slot    string `json:"slot"`
	Value   string `json:"value"`
}

type oracleChangedAccount struct {
	Address    string `json:"address"`
	CodeHash   string `json:"code_hash"`
	Commitment string `json:"commitment"`
}

type oracleExpected struct {
	Name        string                 `json:"name"`
	Status      string                 `json:"status"`
	Output      string                 `json:"output"`
	GasUsed     uint64                 `json:"gas_used"`
	GasRefunded int64                  `json:"gas_refunded"`
	Logs        []replayLog            `json:"logs"`
	Storage     []oracleSlot           `json:"storage"`
	Accounts    []oracleChangedAccount `json:"accounts"`
}

type oracleState struct {
	*memstate.State
	commitments map[primitives.Address]primitives.Hash
	original    map[primitives.Address]primitives.Hash
}

func (s *oracleState) ConfigCommitment(addr primitives.Address) primitives.Hash {
	return s.commitments[addr]
}

func (s *oracleState) SetConfigCommitment(addr primitives.Address, c primitives.Hash) {
	s.commitments[addr] = c
}

const oracleFileCount = 26

const oracleFilesMax = 2 * oracleFileCount

const _ = uint(oracleFilesMax - oracleFileCount)

const oracleArchive = "testdata/oracle.tar.gz"

func readOracleArchive() map[string][]string {
	raw, err := os.ReadFile(oracleArchive)
	assert.NoError(err, "read "+oracleArchive)
	zr, err := gzip.NewReader(bytes.NewReader(raw))
	assert.NoError(err, "gunzip "+oracleArchive)
	tr := tar.NewReader(zr)
	files := map[string][]string{}
	for range oracleFilesMax {
		h, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		assert.NoError(err, "read "+oracleArchive)
		if h.Typeflag != tar.TypeReg {
			continue
		}
		body, err := io.ReadAll(tr)
		assert.NoError(err, "read "+h.Name)
		var lines []string
		for _, l := range strings.Split(string(body), "\n") {
			if l = strings.TrimSpace(l); l != "" {
				lines = append(lines, l)
			}
		}
		files[h.Name] = lines
	}
	assert.Equal(oracleFileCount, len(files), "oracle archive file count")
	return files
}

var specForks = map[string]hardfork.Fork{
	"T0": hardfork.T0, "T1": hardfork.T1, "T1A": hardfork.T1A, "T1B": hardfork.T1B,
	"T1C": hardfork.T1C, "T2": hardfork.T2, "T3": hardfork.T3, "T4": hardfork.T4,
	"T5": hardfork.T5, "T6": hardfork.T6, "T7": hardfork.T7, "T8": hardfork.T8,
	"T9": hardfork.T9, "T10": hardfork.T10, "T11": hardfork.T11, "T12": hardfork.T12,
	"T13": hardfork.T13, "T14": hardfork.T14,
}

func oracleSets(files map[string][]string) [][2]string {
	var sets [][2]string
	for _, name := range slices.Sorted(maps.Keys(files)) {
		if base, ok := strings.CutSuffix(name, "cases.jsonl"); ok {
			sets = append(sets, [2]string{name, base + "expected.jsonl"})
		}
	}
	return sets
}

func knownOracle() map[string]bool {
	known := map[string]bool{}
	raw, err := os.ReadFile("testdata/oracle_known.txt")
	if err != nil {
		return known
	}
	for _, l := range strings.Split(string(raw), "\n") {
		if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
			known[l] = true
		}
	}
	return known
}

func TestOracle(t *testing.T) {
	files := readOracleArchive()
	known := knownOracle()
	var passed, failed, tolerated int
	var unexpected []string
	var report strings.Builder
	for _, set := range oracleSets(files) {
		cases, expected := files[set[0]], files[set[1]]
		assert.Equal(len(cases), len(expected), "case and expectation counts "+set[0])
		for i := range cases {
			var c oracleCase
			var e oracleExpected
			assert.NoError(json.Unmarshal([]byte(cases[i]), &c), "parse case")
			assert.NoError(json.Unmarshal([]byte(expected[i]), &e), "parse expected")
			assert.Equal(c.Name, e.Name, "case order")
			diff := runOracle(c, e)
			if diff == "" {
				passed++
				continue
			}
			failed++
			fmt.Fprintf(&report, "%s [%s]: %s\n", c.Name, c.Spec, diff)
			if known[c.Name] {
				tolerated++
				continue
			}
			unexpected = append(unexpected, c.Name+": "+diff)
		}
	}
	if path := os.Getenv("GOEMPO_ORACLE_REPORT"); path != "" {
		assert.NoError(os.WriteFile(path, []byte(report.String()), 0o644), "write report")
	}
	t.Logf("oracle: %d passed, %d differ (%d known)", passed, failed, tolerated)
	if len(unexpected) > 0 {
		t.Errorf("%d cases differ from the reference:\n%s", len(unexpected), strings.Join(unexpected[:min(len(unexpected), 40)], "\n"))
	}
}

func seedOracle(c oracleCase) *oracleState {
	st := &oracleState{State: memstate.New(), commitments: map[primitives.Address]primitives.Hash{}}
	for _, a := range c.Accounts {
		acct := memstate.Account{Storage: map[primitives.Hash]u256.Int{}}
		if a.Code != nil {
			acct.Code = mustBytes(*a.Code)
		}
		for _, kv := range a.Storage {
			acct.Storage[mustWord(kv[0]).Bytes32()] = mustWord(kv[1])
		}
		st.Put(mustAddr(a.Address), acct)
		if a.Commitment != nil {
			st.commitments[mustAddr(a.Address)] = mustHash(*a.Commitment)
		}
	}
	st.original = map[primitives.Address]primitives.Hash{}
	for k, v := range st.commitments {
		st.original[k] = v
	}
	for _, tr := range c.Transient {
		st.SetTransientStorage(mustAddr(tr.Address), mustWord(tr.Slot).Bytes32(), mustWord(tr.Value))
	}
	st.WarmAddress(mustAddr(c.Call.Caller))
	return st
}

func runOracle(c oracleCase, e oracleExpected) string {
	fork, ok := specForks[c.Spec]
	assert.Ok(ok, "known spec "+c.Spec)
	code := mustAddr(c.Call.CodeAddress)
	set := precompiles.NewSet(fork, nil)
	p, found := set.Lookup(code)
	if e.Status == "not-a-precompile" || !found {
		if (e.Status == "not-a-precompile") == found {
			return fmt.Sprintf("precompile present %v, expected %s", found, e.Status)
		}
		return ""
	}
	st := seedOracle(c)
	pre := snapshotStorage(st)
	block := &evm.BlockContext{Number: c.Block.Number, Time: c.Block.Timestamp, Coinbase: mustAddr(c.Block.Beneficiary),
		GetHash: func(uint64) primitives.Hash { return primitives.Hash{} }}
	cfg := evm.NewConfig(evm.Osaka, u256.FromUint64(uint64(hardfork.MainnetChainID)))
	vm := evm.New(evm.Context{State: st, Block: block, Tx: &evm.TxContext{}, Config: cfg})
	kind := evm.KindCall
	if c.Call.Static {
		kind = evm.KindStaticCall
	}
	res := p.Run(&evm.PrecompileCall{EVM: vm, Kind: kind, Caller: mustAddr(c.Call.Caller), Address: mustAddr(c.Call.Target),
		CodeAddress: code, Input: mustBytes(c.Call.Data), Gas: c.Call.Gas, Static: c.Call.Static})
	status := "halt"
	if res.Status == evm.StatusReturn {
		status = "success"
	}
	if res.Status == evm.StatusRevert {
		status = "revert"
	}
	if e.Status == "fatal" {
		if status != "halt" {
			return "status " + status + ", expected fatal"
		}
		return ""
	}
	if status != e.Status {
		return fmt.Sprintf("status %s (output %x gas %d), expected %s (output %s gas %d)", status, res.Output, res.GasUsed, e.Status, e.Output, e.GasUsed)
	}
	if status == "halt" {
		return ""
	}
	want := strings.TrimPrefix(e.Output, "0x")
	if hex.EncodeToString(res.Output) != want {
		return fmt.Sprintf("output %x, expected %s", res.Output, want)
	}
	if res.GasUsed != e.GasUsed {
		return fmt.Sprintf("gas %d, expected %d (delta %d)", res.GasUsed, e.GasUsed, int64(res.GasUsed)-int64(e.GasUsed))
	}
	if status != "success" {
		return ""
	}
	if st.Refund() != e.GasRefunded {
		return fmt.Sprintf("refund %d, expected %d", st.Refund(), e.GasRefunded)
	}
	if d := compareOracleLogs(st.Logs(), e.Logs); d != "" {
		return d
	}
	if d := compareOracleStorage(storageDiff{pre: pre, post: snapshotStorage(st)}, e.Storage); d != "" {
		return d
	}
	return compareOracleAccounts(c, st, e.Accounts)
}

func compareOracleLogs(got []evm.Log, want []replayLog) string {
	if len(got) != len(want) {
		return fmt.Sprintf("%d logs, expected %d", len(got), len(want))
	}
	for i, w := range want {
		g := got[i]
		same := g.Address == mustAddr(w.Address) && len(g.Topics) == len(w.Topics) && bytes.Equal(g.Data, mustBytes(w.Data))
		for j := 0; same && j < len(w.Topics); j++ {
			same = g.Topics[j] == mustHash(w.Topics[j])
		}
		if !same {
			return fmt.Sprintf("log %d differs: got %x %x, expected %s %s", i, g.Topics, g.Data, w.Topics, w.Data)
		}
	}
	return ""
}

type slotID string

func slotOf(addr primitives.Address, key primitives.Hash) slotID {
	return slotID(hex.EncodeToString(addr[:]) + "/" + hex.EncodeToString(key[:]))
}

func snapshotStorage(st *oracleState) map[slotID]u256.Int {
	out := map[slotID]u256.Int{}
	for _, a := range st.Addresses() {
		acct, _ := st.Get(a)
		for k, v := range acct.Storage {
			out[slotOf(a, k)] = v
		}
	}
	return out
}

type storageDiff struct {
	pre  map[slotID]u256.Int
	post map[slotID]u256.Int
}

func compareOracleStorage(d storageDiff, want []oracleSlot) string {
	pre, post := d.pre, d.post
	changed := map[slotID]u256.Int{}
	for _, k := range slices.Sorted(maps.Keys(post)) {
		if v := post[k]; pre[k] != v {
			changed[k] = v
		}
	}
	for _, k := range slices.Sorted(maps.Keys(pre)) {
		if _, ok := post[k]; !ok {
			changed[k] = u256.Int{}
		}
	}
	for _, w := range want {
		id := slotOf(mustAddr(w.Address), mustWord(w.Slot).Bytes32())
		got, ok := changed[id]
		if !ok {
			got = post[id]
		}
		if got != mustWord(w.Value) {
			return fmt.Sprintf("slot %s/%s = %x, expected %s", w.Address, w.Slot, got.Bytes32(), w.Value)
		}
		delete(changed, id)
	}
	if len(changed) > 0 {
		var extra []string
		for _, k := range slices.Sorted(maps.Keys(changed)) {
			extra = append(extra, fmt.Sprintf("%s=%x", k, changed[k].Bytes32()))
		}
		return fmt.Sprintf("%d unexpected slot changes: %s", len(extra), strings.Join(extra[:min(len(extra), 4)], " "))
	}
	return ""
}

func compareOracleAccounts(c oracleCase, st *oracleState, want []oracleChangedAccount) string {
	preCode := map[primitives.Address][]byte{}
	for _, a := range c.Accounts {
		if a.Code != nil {
			preCode[mustAddr(a.Address)] = mustBytes(*a.Code)
		}
	}
	got := map[primitives.Address]bool{}
	for _, a := range st.Addresses() {
		acct, _ := st.Get(a)
		if !bytes.Equal(acct.Code, preCode[a]) {
			got[a] = true
		}
	}
	for a, v := range st.commitments {
		if st.original[a] != v {
			got[a] = true
		}
	}
	if len(got) != len(want) {
		return fmt.Sprintf("%d accounts changed, expected %d", len(got), len(want))
	}
	for _, w := range want {
		a := mustAddr(w.Address)
		acct, _ := st.Get(a)
		if !got[a] || primitives.Hash(keccak.Sum256(acct.Code)) != mustHash(w.CodeHash) || st.commitments[a] != mustHash(w.Commitment) {
			return fmt.Sprintf("account %s differs: code hash %x commitment %x", w.Address, keccak.Sum256(acct.Code), st.commitments[a])
		}
	}
	return ""
}
