// Command gen writes keccakf_amd64.s: Keccak-f[1600] on eight states at once,
// lane i of state k in qword k of register Zi, with AVX-512 ternary logic and
// rotates. Run it from the package directory: go run _asm/gen.go
package main

import (
	"fmt"
	"os"
	"strings"
)

var rotations = [25]int{
	0, 1, 62, 28, 27,
	36, 44, 6, 55, 20,
	3, 10, 43, 25, 39,
	41, 45, 15, 21, 8,
	18, 2, 61, 56, 14,
}

var roundConstants = [24]uint64{
	0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
	0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
	0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
	0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
	0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
	0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
}

func reg(r int) string { return fmt.Sprintf("Z%d", r) }

func main() {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("// Code generated by _asm/gen.go. DO NOT EDIT.")
	w("")
	w("//go:build amd64 && !purego")
	w("")
	w("#include \"textflag.h\"")
	w("")
	for i, rc := range roundConstants {
		w("DATA roundConstants<>+%d(SB)/8, $0x%016x", 8*i, rc)
	}
	w("GLOBL roundConstants<>(SB), RODATA|NOPTR, $%d", 8*len(roundConstants))
	w("")
	w("// func keccakF1600x8(a *[25][8]uint64)")
	w("TEXT ·keccakF1600x8(SB), NOSPLIT, $0-8")
	w("\tMOVQ a+0(FP), AX")
	// lane[i] is the register holding lane i = x + 5y.
	var lane [25]int
	for i := 0; i < 25; i++ {
		lane[i] = i
		w("\tVMOVDQU64 %d(AX), %s", 64*i, reg(i))
	}
	free := []int{25, 26, 27, 28, 29, 30}
	for round := 0; round < 24; round++ {
		w("\t// round %d", round)
		c := free[:5]
		t := free[5]
		for x := 0; x < 5; x++ {
			w("\tVMOVDQA64 %s, %s", reg(lane[x]), reg(c[x]))
			w("\tVPTERNLOGQ $0x96, %s, %s, %s", reg(lane[x+10]), reg(lane[x+5]), reg(c[x]))
			w("\tVPTERNLOGQ $0x96, %s, %s, %s", reg(lane[x+20]), reg(lane[x+15]), reg(c[x]))
		}
		for x := 0; x < 5; x++ {
			w("\tVPROLQ $1, %s, %s", reg(c[(x+1)%5]), reg(t))
			for y := 0; y < 5; y++ {
				w("\tVPTERNLOGQ $0x96, %s, %s, %s", reg(t), reg(c[(x+4)%5]), reg(lane[x+5*y]))
			}
		}
		var next [25]int
		for x := 0; x < 5; x++ {
			for y := 0; y < 5; y++ {
				r := lane[x+5*y]
				if rot := rotations[x+5*y]; rot != 0 {
					w("\tVPROLQ $%d, %s, %s", rot, reg(r), reg(r))
				}
				nx, ny := y, (2*x+3*y)%5
				next[nx+5*ny] = r
			}
		}
		lane = next
		for y := 0; y < 5; y++ {
			t0, t1 := c[0], c[1]
			w("\tVMOVDQA64 %s, %s", reg(lane[5*y]), reg(t0))
			w("\tVMOVDQA64 %s, %s", reg(lane[5*y+1]), reg(t1))
			for x := 0; x < 5; x++ {
				b1, b2 := lane[5*y+(x+1)%5], lane[5*y+(x+2)%5]
				if x == 3 {
					b2 = t0
				}
				if x == 4 {
					b1, b2 = t0, t1
				}
				w("\tVPTERNLOGQ $0xd2, %s, %s, %s", reg(b2), reg(b1), reg(lane[5*y+x]))
			}
		}
		w("\tVPXORQ.BCST roundConstants<>+%d(SB), %s, %s", 8*round, reg(lane[0]), reg(lane[0]))
	}
	for i := 0; i < 25; i++ {
		w("\tVMOVDQU64 %s, %d(AX)", reg(lane[i]), 64*i)
	}
	w("\tVZEROUPPER")
	w("\tRET")
	if err := os.WriteFile("keccakf_amd64.s", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
