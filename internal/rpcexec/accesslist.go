func (x *Executor) BlockAccessList(number uint64) (rpc.AccessListData, error) {
	release := x.acquire()
	defer release()
	run, err := x.replayBlock(number, tracing.StepOptions{})
	if err != nil {
		return rpc.AccessListData{}, err
	}
	txs := make([]tracing.IndexedTrace, 0, len(run.user))
	for u, i := range run.user {
		txs = append(txs, tracing.IndexedTrace{Index: uint64(i) + 1, Trace: run.session.Traces()[u]})
	}
	always := append([]evm.Address{evm.Address(run.data.Block.Header.Inner.Beneficiary)}, accessListSystemAddresses...)
	bal := tracing.BuildAccessList(txs, always)
	return rpc.AccessListData{JSON: bal.JSON(), RLP: bal.RLP()}, nil
}
